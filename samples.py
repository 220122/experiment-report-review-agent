def get_sample(index: int) -> Dict[str, str]:
    """按索引取示例（越界时返回第一个，保证界面不崩）。"""
    if not SAMPLES:
        return {"name": "", "kind": "bad", "standard": "", "report": "", "note": ""}
    if index < 0 or index >= len(SAMPLES):
        index = 0
    return SAMPLES[index]


def kind_label(kind: str) -> str:
    """把 kind 转成中文标签。"""
    return {
        "good": "✅ 正确范例",
        "bad": "❌ 含典型错误",
        "violation": "🚨 学术不端（触发护栏）",
    }.get(kind, "❓ 未知")


def count_by_kind() -> Dict[str, int]:
    """统计各类型示例数量，用于界面提示。"""
    result = {"good": 0, "bad": 0, "violation": 0}
    for item in SAMPLES:
        result[item["kind"]] = result.get(item["kind"], 0) + 1
    return result
